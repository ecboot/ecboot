-- ============================================================
-- V27 休眠账户风控 (产品决策 2026-09-18)
-- 分级基线(时长决定核身强度,行为信号决定是否升级):
--   ≥90天  登录强制短信验证码(不再静默放行)
--   ≥180天 休眠标记:敏感操作(改绑/提现/余额消费)二次核身+资金限频
--   ≥365天 深度休眠:提现/余额动用前重新实名核身;进入清理候选池
--   ≥2年   匿名化候选(数据最小化)——但有余额/未结算佣金/
--          未完结订单的账号绝不可清理(资金安全 > 合规处置)
-- 判定口径: 以 last_active_at 为准(小程序静默登录会掩盖
--   "未登录"——用户可能一直"被登录"而无感知)
-- 拦截原则: 久未登录后的异常行为才是威胁(新设备/异地/
--   密码错后成功/登录即改绑提现), 天数只是默认核身等级
-- ============================================================

ALTER TABLE `user`
  ADD COLUMN `last_login_at`  DATETIME NULL DEFAULT NULL COMMENT '最后登录时间(休眠分级依据;登录链路一次命中,免login_log聚合)' AFTER `level`,
  ADD COLUMN `last_active_at` DATETIME NULL DEFAULT NULL COMMENT '最后活跃时间(登录/下单/浏览任一;休眠判定以此为准)' AFTER `last_login_at`;

-- 风控规则类型扩位: 休眠账户分级(阈值/动作可配置,规则化而非硬编码)
ALTER TABLE `risk_rule`
  MODIFY COLUMN `rule_type` TINYINT NOT NULL COMMENT '规则类型:1黑名单 2高频下单 3异常领券 4佣金套利特征 5休眠账户分级';
